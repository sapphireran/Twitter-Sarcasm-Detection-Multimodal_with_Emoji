#!/usr/bin/env python3
"""Census the train / test / subtest CSVs and optionally write a markdown report."""

from __future__ import annotations

import argparse
import statistics
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from examples.lib.dataset_io import Split, load_all_splits, overlap_count
from examples.lib.emoji_extract import extract_emojis, has_high_codepoint
from examples.lib.tweet_tokenize import tokenize_tweet


def _hashtag_counts(split: Split) -> dict[str, int]:
    not_tag = sarc_tag = hash_any = 0
    for text, _ in split.pairs():
        tokens = tokenize_tweet(text)
        tags = [tok for tok in tokens if tok.startswith("#")]
        if tags:
            hash_any += 1
        if "#not" in tags:
            not_tag += 1
        if any(tok.startswith("#sarcas") for tok in tags):
            sarc_tag += 1
    return {"hash_any": hash_any, "not_tag": not_tag, "sarc_tag": sarc_tag}


def _class_condition(split: Split, predicate) -> tuple[int, int]:
    pos = neg = 0
    for text, label in split.pairs():
        if not predicate(text):
            continue
        if label == 1:
            pos += 1
        else:
            neg += 1
    return pos, neg


def describe_split(split: Split) -> dict[str, object]:
    token_lens = [len(tokenize_tweet(text)) for text in split.texts]
    ws_lens = [len(text.split()) for text in split.texts]
    n_user = sum(1 for text in split.texts if "<user>" in text.casefold())
    n_high = sum(1 for text in split.texts if has_high_codepoint(text))
    n_emoji = sum(1 for text in split.texts if extract_emojis(text))
    tags = _hashtag_counts(split)
    not_pos, not_neg = _class_condition(
        split, lambda t: "#not" in tokenize_tweet(t)
    )
    labels = Counter(split.labels)
    return {
        "n": len(split),
        "n_pos": labels.get(1, 0),
        "n_neg": labels.get(0, 0),
        "pos_rate": split.positive_rate(),
        "mean_tokens": statistics.fmean(token_lens) if token_lens else 0.0,
        "median_tokens": statistics.median(token_lens) if token_lens else 0,
        "max_tokens": max(token_lens) if token_lens else 0,
        "mean_ws": statistics.fmean(ws_lens) if ws_lens else 0.0,
        "n_user": n_user,
        "n_high": n_high,
        "n_emoji": n_emoji,
        "hash_any": tags["hash_any"],
        "not_tag": tags["not_tag"],
        "sarc_tag": tags["sarc_tag"],
        "not_pos": not_pos,
        "not_neg": not_neg,
        "unique": len(set(split.texts)),
    }


def render_report(splits: dict[str, Split]) -> str:
    train, test, sub = splits["train"], splits["test"], splits["subtest"]
    stats = {name: describe_split(split) for name, split in splits.items()}
    lines = [
        "# Dataset report",
        "",
        "Generated by `examples/inspect_dataset.py` from the checked-in CSVs.",
        "",
        "## Sizes and labels",
        "",
        "| Split | Rows | Unique | Sarcastic | Non-sarcastic | Pos rate |",
        "| --- | ---: | ---: | ---: | ---: | ---: |",
    ]
    for name in ("train", "test", "subtest"):
        s = stats[name]
        lines.append(
            f"| {name} | {s['n']} | {s['unique']} | {s['n_pos']} | {s['n_neg']} "
            f"| {s['pos_rate']:.3f} |"
        )
    lines += [
        "",
        "## Split overlap",
        "",
        f"- subtest strings also in test: **{overlap_count(sub, test)} / {len(sub)}**",
        f"- test strings also in train: **{overlap_count(test, train)} / {len(test)}**",
        f"- subtest strings also in train: **{overlap_count(sub, train)} / {len(sub)}**",
        f"- duplicate rows inside train: **{stats['train']['n'] - stats['train']['unique']}**",
        "",
        "## Surface cues",
        "",
        "| Split | `#` any | `#not` | `#sarcas*` | `<user>` | high codepoint | extracted emoji |",
        "| --- | ---: | ---: | ---: | ---: | ---: | ---: |",
    ]
    for name in ("train", "test", "subtest"):
        s = stats[name]
        lines.append(
            f"| {name} | {s['hash_any']} | {s['not_tag']} | {s['sarc_tag']} "
            f"| {s['n_user']} | {s['n_high']} | {s['n_emoji']} |"
        )
    lines += [
        "",
        "## `#not` by class",
        "",
        "| Split | sarcastic with `#not` | non-sarcastic with `#not` |",
        "| --- | ---: | ---: |",
    ]
    for name in ("train", "test", "subtest"):
        s = stats[name]
        lines.append(f"| {name} | {s['not_pos']} | {s['not_neg']} |")
    lines += [
        "",
        "## Token length (Tweet-aware)",
        "",
        "| Split | mean | median | max | mean whitespace |",
        "| --- | ---: | ---: | ---: | ---: |",
    ]
    for name in ("train", "test", "subtest"):
        s = stats[name]
        lines.append(
            f"| {name} | {s['mean_tokens']:.2f} | {s['median_tokens']} "
            f"| {s['max_tokens']} | {s['mean_ws']:.2f} |"
        )
    lines += [
        "",
        "## Notes",
        "",
        "- High-codepoint uses `ord(c) > 0x2710`, the same cheap filter that",
        "  reconstructs subtest from test.",
        "- `#not` is tokenized as a hashtag, not as the English word *not*.",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=ROOT / "dataset")
    parser.add_argument("--out", type=Path, default=None)
    args = parser.parse_args(argv)

    splits = load_all_splits(args.root)
    report = render_report(splits)
    print(report)
    if args.out is not None:
        args.out.parent.mkdir(parents=True, exist_ok=True)
        args.out.write_text(report, encoding="utf-8")
        print(f"\nWrote {args.out}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
